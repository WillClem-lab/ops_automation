@mcp.tool()
def query_user_lifecycle_status(user_principal_name: str = "") -> str:
    """
    Queries the sample users dataset (sample_users.csv) to return employment status,
    department, and role assignment. If UPN is omitted, returns all users.
    """
    csv_path = "generic-operations/examples/sample_users.csv"
    if not os.path.exists(csv_path):
        return json.dumps({"error": f"Dataset file not found at {csv_path}"})

    results = []
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if not user_principal_name or user_principal_name.lower() in row.get("UserPrincipalName", "").lower():
                results.append(row)

    if not results:
        return json.dumps({"message": f"No user records found matching '{user_principal_name}'"})

    return json.dumps(results, indent=2)


@mcp.tool()
def get_remediation_audit_logs(limit: int = 5) -> str:
    """
    Retrieves recent automated endpoint remediation audit logs generated by AGENT-REMED-003.
    Returns JSON array of timestamped evaluation events.
    """
    log_path = "ai-governance/remediation_audit.log"
    if not os.path.exists(log_path):
        return json.dumps({"message": "No remediation audit log file found yet."})

    logs = []
    with open(log_path, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                try:
                    logs.append(json.loads(line.strip()))
                except json.JSONDecodeError:
                    continue

    recent_logs = logs[-limit:] if limit > 0 else logs
    return json.dumps(recent_logs, indent=2)


@mcp.tool()
def check_compliance_framework_mapping(framework_name: str) -> str:
    """
    Returns mapped automation assets and script runbooks for a specific regulatory standard
    (e.g., 'SOC 2', 'HIPAA', 'NIST', 'ISO 27001').
    """
    mappings = {
        "SOC 2": {
            "controls": ["CC6.1 - Logical Access", "CC6.3 - User Deprovisioning", "CC6.8 - Flaw Remediation"],
            "assets": ["generic-operations/Invoke-UserOffboarding.ps1", "ai-governance/workflows/remediation_agent.py", "docs/SOP_Runbook_Template.md"]
        },
        "HIPAA": {
            "controls": [" 164.312(a)(1) - Access Control", " 164.312(b) - Audit Controls", " 164.312(a)(2)(iv) - Encryption"],
            "assets": ["healthcare-compliance/Invoke-HIPAAAccessAudit.ps1", "ai-governance/AI_Acceptable_Use_Policy.md", "ai-governance/workflows/saas_access_agent.py"]
        },
        "NIST RMF": {
            "controls": ["AC-2 - Account Management", "SI-2 - Flaw Remediation", "IA-2 - Identification and Auth"],
            "assets": ["generic-operations/Get-EndpointComplianceStatus.ps1", "ai-governance/workflows/kb_generator_agent.py"]
        }
    }

    key = framework_name.upper().strip()
    for fw, details in mappings.items():
        if fw in key or key in fw:
            return json.dumps({"framework": fw, "mapped_data": details}, indent=2)

    return json.dumps({"error": f"Framework '{framework_name}' not recognized. Supported: SOC 2, HIPAA, NIST RMF."})

